import { Post, Reply, ContentBlock } from '../types';

// Helper: wrap a plain-text string in a ContentBlock[]
const textBlock = (text: string): ContentBlock[] => [
  { type: 'text', text, format: 'plain' },
];

// Helper: video content block + optional text
const videoBlock = (url: string, thumbnailUrl: string, text?: string): ContentBlock[] => {
  const blocks: ContentBlock[] = [
    { type: 'video', mediaId: '', url, thumbnailUrl },
  ];
  if (text) blocks.push({ type: 'text', text, format: 'plain' });
  return blocks;
};

